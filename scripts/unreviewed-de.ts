/**
 * Renders i18n/UNREVIEWED_DE.md: every German string on the site, for the user to review. There is no approved German
 * source, so all of it is our translation of the approved EN.
 *   - Page copy: content/de/unreviewed.ts (`UNREVIEWED_DE`, including the site-wide strings of content/de/site.ts).
 *   - UI microcopy: every key of i18n/locales/de.json, next to its value in en.json.
 *
 * Run `npm run unreviewed:de` after changing a translation and commit the result. A unit test fails when the
 * committed file differs from `renderUnreviewedDeMd()`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { UNREVIEWED_DE } from '../content/de/unreviewed.ts'

/** `import.meta.dirname` under Node; vitest's nuxt environment provides `__dirname` instead. */
const here: string = import.meta.dirname ?? __dirname
const root = resolve(here, '..')
export const UNREVIEWED_DE_MD_PATH = resolve(root, 'i18n/UNREVIEWED_DE.md')

function flatten(o: unknown, prefix = '', acc: Record<string, string> = {}): Record<string, string> {
  for (const [k, v] of Object.entries(o as Record<string, unknown>)) {
    const p = prefix ? `${prefix}.${k}` : k
    if (typeof v === 'string') acc[p] = v
    else flatten(v, p, acc)
  }
  return acc
}

const readMessages = (locale: 'en' | 'de') =>
  flatten(JSON.parse(readFileSync(resolve(root, `i18n/locales/${locale}.json`), 'utf8')))

const cell = (s: string) => s.replace(/\|/g, '\\|')
const row = (cells: string[]) => `| ${cells.join(' | ')} |`

export function renderUnreviewedDeMd(): string {
  const en = readMessages('en')
  const de = readMessages('de')
  const uiKeys = Object.keys(de)
  const pages = [...new Set(UNREVIEWED_DE.map((e) => e.page))]
  const same = UNREVIEWED_DE.filter((e) => e.de === e.en).length

  const out: string[] = [
    '# German copy awaiting review',
    '',
    '<!-- Generated by `npm run unreviewed:de` (scripts/unreviewed-de.ts). Do not edit by hand. -->',
    '',
    'There is **no approved German source** in `MOESA_Website_Package_v1.0`. Every German string on the site is our',
    'translation of the approved English (`content/en`, formal "Sie"); it was never taken from the TR copy or from the',
    'canvas `i18n.js`. All of it is listed below for review before the German site goes live.',
    '',
    `## Page copy (${UNREVIEWED_DE.length} strings)`,
    '',
    'Source: `content/de/unreviewed.ts`; the strings are used verbatim in `content/de/*.ts`. The path is the field in the',
    'page module (legal sections are addressed by id); `site` is the footer descriptor (`content/de/site.ts`).',
    `${same} strings are deliberately the same as in EN (company name, address, email, the legal draft status, established`,
    'English terms such as "Digital Commerce & Commercial Intelligence"). Links, slugs and ids are not translated and',
    'not listed. Legal pages remain drafts: they keep the package status line in the draft chip and every',
    '"OPEN / AÇIK - " item (both shown on Preview deployments only), and the German Impressum and Datenschutzerklärung',
    'need a German legal review before launch.',
  ]
  for (const page of pages) {
    const entries = UNREVIEWED_DE.filter((e) => e.page === page)
    out.push('', `### ${page} (${entries.length})`, '', row(['Path', 'EN', 'DE']), row(['---', '---', '---']))
    for (const e of entries) out.push(row([`\`${e.path}\``, cell(e.en), cell(e.de)]))
  }

  out.push(
    '',
    `## UI microcopy (${uiKeys.length} strings)`,
    '',
    'Source: every key of `i18n/locales/de.json`, next to its EN value from `i18n/locales/en.json`. The `nav.header.*`',
    'keys are the labels of the desktop header bar; `{…}` are placeholders filled in at runtime.',
    '',
    row(['Key', 'EN', 'DE']),
    row(['---', '---', '---']),
  )
  for (const k of uiKeys) {
    if (en[k] === undefined) throw new Error(`i18n/locales/de.json: ${k} is not in en.json`)
    out.push(row([`\`${k}\``, cell(en[k]), cell(de[k]!)]))
  }
  return `${out.join('\n')}\n`
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]).toLowerCase() : ''
if (import.meta.filename && invokedPath === import.meta.filename.toLowerCase()) {
  writeFileSync(UNREVIEWED_DE_MD_PATH, renderUnreviewedDeMd(), 'utf8')
  const ui = Object.keys(readMessages('de')).length
  console.log(`Wrote ${UNREVIEWED_DE_MD_PATH}: ${UNREVIEWED_DE.length} page strings, ${ui} UI strings.`)
}
