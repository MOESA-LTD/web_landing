/**
 * Renders i18n/UNREVIEWED_TR.md: every Turkish string we translated ourselves, for the user to review.
 *   - Page copy: content/tr/unreviewed.ts (`UNREVIEWED_TR`).
 *   - UI microcopy: the keys in i18n/unreviewed-ui.ts, with their values from i18n/locales/{en,tr}.json.
 *
 * Run `npm run unreviewed:tr` after changing a translation and commit the result. A unit test fails when
 * the committed file differs from `renderUnreviewedMd()`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { UNREVIEWED_TR } from '../content/tr/unreviewed.ts'
import { UNREVIEWED_UI_KEYS } from '../i18n/unreviewed-ui.ts'

/** `import.meta.dirname` under Node; vitest's nuxt environment provides `__dirname` instead. */
const here: string = import.meta.dirname ?? __dirname
const root = resolve(here, '..')
export const UNREVIEWED_MD_PATH = resolve(root, 'i18n/UNREVIEWED_TR.md')

function flatten(o: unknown, prefix = '', acc: Record<string, string> = {}): Record<string, string> {
  for (const [k, v] of Object.entries(o as Record<string, unknown>)) {
    const p = prefix ? `${prefix}.${k}` : k
    if (typeof v === 'string') acc[p] = v
    else flatten(v, p, acc)
  }
  return acc
}

const readMessages = (locale: 'en' | 'tr') =>
  flatten(JSON.parse(readFileSync(resolve(root, `i18n/locales/${locale}.json`), 'utf8')))

const cell = (s: string) => s.replace(/\|/g, '\\|')
const row = (cells: string[]) => `| ${cells.join(' | ')} |`

export function renderUnreviewedMd(): string {
  const en = readMessages('en')
  const tr = readMessages('tr')
  const pages = [...new Set(UNREVIEWED_TR.map((e) => e.page))]

  const out: string[] = [
    '# Turkish copy awaiting review',
    '',
    '<!-- Generated by `npm run unreviewed:tr` (scripts/unreviewed-tr.ts). Do not edit by hand. -->',
    '',
    'Every Turkish string below has **no source** in `MOESA_Website_Package_v1.0/content/tr`. We translated it from the',
    'approved English (formal Turkish, "siz" form, the terminology of the approved TR files). Please review it before launch.',
    'Approved TR text from the package is never changed and is not listed here.',
    '',
    `## Page copy (${UNREVIEWED_TR.length} strings)`,
    '',
    'Source: `content/tr/unreviewed.ts`; the strings are used verbatim in `content/tr/*.ts`. The path is the field in the',
    'page module (legal sections are addressed by id). Where the TR package condensed an EN list into one sentence, that',
    'approved sentence is kept (field `condensed`) and the list items below are added next to it. Legal pages remain',
    'drafts ("DRAFT / TASLAK - LEGAL REVIEW REQUIRED"); their translated sections need legal review like the EN ones.',
  ]
  for (const page of pages) {
    const entries = UNREVIEWED_TR.filter((e) => e.page === page)
    out.push('', `### ${page} (${entries.length})`, '', row(['Path', 'EN', 'TR']), row(['---', '---', '---']))
    for (const e of entries) out.push(row([`\`${e.path}\``, cell(e.en), cell(e.tr)]))
  }

  out.push(
    '',
    `## UI microcopy (${UNREVIEWED_UI_KEYS.length} strings)`,
    '',
    'Source: the keys in `i18n/unreviewed-ui.ts`; the values come from `i18n/locales/{en,tr}.json`.',
    '',
    'Not listed here, because they come from the package TR md:',
    '- nav labels, footer legal links, breadcrumb "Home"/"Services" and the service names: the TR page titles',
    '- header CTA: the TR home CTA label',
    '- form labels (name, company, work email, country, service, brief) and `form.briefHelp`: TR contact.md',
    '- `status.draft` / `status.open`: the "TASLAK" / "AÇIK" of the package status lines',
    '- `form.serviceOptions.*` (except "other"): the TR contact.md service list, capitalised for use as option labels',
    '- `cookie.strictlyNecessary`: the TR cookie-policy.md category "Zorunlu"',
    '- `footer.companyLine`: the TR legal-notice.md also writes "Company ID" and "VAT" in English',
    '',
    row(['Key', 'EN', 'TR']),
    row(['---', '---', '---']),
  )
  for (const k of UNREVIEWED_UI_KEYS) {
    if (en[k] === undefined || tr[k] === undefined) throw new Error(`UNREVIEWED_UI_KEYS: ${k} is missing from a locale json`)
    out.push(row([`\`${k}\``, cell(en[k]), cell(tr[k])]))
  }
  return `${out.join('\n')}\n`
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]).toLowerCase() : ''
if (import.meta.filename && invokedPath === import.meta.filename.toLowerCase()) {
  writeFileSync(UNREVIEWED_MD_PATH, renderUnreviewedMd(), 'utf8')
  console.log(`Wrote ${UNREVIEWED_MD_PATH}: ${UNREVIEWED_TR.length} page strings, ${UNREVIEWED_UI_KEYS.length} UI strings.`)
}
