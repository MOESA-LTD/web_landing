/**
 * Renders i18n/UNREVIEWED_BG.md: every Bulgarian string on the site, for the user to review. There is no approved
 * Bulgarian source, so all of it is our translation of the approved EN.
 *   - Page copy: content/bg/unreviewed.ts (`UNREVIEWED_BG`, including the site-wide strings of content/bg/site.ts).
 *   - Legal text written after the legal review: content/legal-revisions.ts, rendered in i18n/UNREVIEWED_LEGAL.md.
 *   - UI microcopy: every key of i18n/locales/bg.json, next to its value in en.json.
 *
 * Run `npm run unreviewed:bg` after changing a translation and commit the result. A unit test fails when the
 * committed file differs from `renderUnreviewedBgMd()`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { UNREVIEWED_BG } from '../content/bg/unreviewed.ts'

/** `import.meta.dirname` under Node; vitest's nuxt environment provides `__dirname` instead. */
const here: string = import.meta.dirname ?? __dirname
const root = resolve(here, '..')
export const UNREVIEWED_BG_MD_PATH = resolve(root, 'i18n/UNREVIEWED_BG.md')

function flatten(o: unknown, prefix = '', acc: Record<string, string> = {}): Record<string, string> {
  for (const [k, v] of Object.entries(o as Record<string, unknown>)) {
    const p = prefix ? `${prefix}.${k}` : k
    if (typeof v === 'string') acc[p] = v
    else flatten(v, p, acc)
  }
  return acc
}

const readMessages = (locale: 'en' | 'bg') =>
  flatten(JSON.parse(readFileSync(resolve(root, `i18n/locales/${locale}.json`), 'utf8')))

const cell = (s: string) => s.replace(/\|/g, '\\|')
const row = (cells: string[]) => `| ${cells.join(' | ')} |`

export function renderUnreviewedBgMd(): string {
  const en = readMessages('en')
  const bg = readMessages('bg')
  const uiKeys = Object.keys(bg)
  const pages = [...new Set(UNREVIEWED_BG.map((e) => e.page))]
  const same = UNREVIEWED_BG.filter((e) => e.bg === e.en).length

  const out: string[] = [
    '# Bulgarian copy awaiting review',
    '',
    '<!-- Generated by `npm run unreviewed:bg` (scripts/unreviewed-bg.ts). Do not edit by hand. -->',
    '',
    'There is **no approved Bulgarian source** in `content/approved`. Every Bulgarian string on the site is',
    'our translation of the approved English (`content/en`, formal "Вие" register); it was never taken from the TR or DE',
    'copy or from the canvas `i18n.js`. All of it is listed below for review before the Bulgarian site goes live',
    '(production keeps it off: `NUXT_PUBLIC_ENABLE_BG = "false"` in `wrangler.toml`; preview deployments show it).',
    '',
    '**Terminology.** English industry terms without a precise Bulgarian equivalent are written in Latin script, without',
    'article or inflection ("sourcing", "Commercial Intelligence", "QA", "D2C", "SEO"); established Bulgarian terms stay',
    '(снабдяване, доставчик, верига на доставки, собствени марки, маркетплейс). See',
    '`docs/superpowers/reviews/2026-11-03-terminology-glossary.md`.',
    '',
    `## Page copy (${UNREVIEWED_BG.length} strings)`,
    '',
    'Source: `content/bg/unreviewed.ts`; the strings are used verbatim in `content/bg/*.ts`. The path is the field in the',
    'page module (legal sections are addressed by id); `site` is the footer descriptor (`content/bg/site.ts`).',
    `${same} strings are deliberately the same as in EN (company name, address, email, the legal draft status). Links,`,
    'slugs and ids are not translated and not listed. Legal pages remain drafts: they keep the package status line in the',
    'draft chip and every "OPEN / AÇIK - " item. The legal text written after the legal review is listed with its EN, TR,',
    'DE and BG in `i18n/UNREVIEWED_LEGAL.md`, not here. The Bulgarian legal pages need a legal review before launch.',
  ]
  for (const page of pages) {
    const entries = UNREVIEWED_BG.filter((e) => e.page === page)
    out.push('', `### ${page} (${entries.length})`, '', row(['Path', 'EN', 'BG']), row(['---', '---', '---']))
    for (const e of entries) out.push(row([`\`${e.path}\``, cell(e.en), cell(e.bg)]))
  }

  out.push(
    '',
    `## UI microcopy (${uiKeys.length} strings)`,
    '',
    'Source: every key of `i18n/locales/bg.json`, next to its EN value from `i18n/locales/en.json`. The `nav.header.*`',
    'keys are the labels of the desktop header bar; `{…}` are placeholders filled in at runtime.',
    '',
    row(['Key', 'EN', 'BG']),
    row(['---', '---', '---']),
  )
  for (const k of uiKeys) {
    if (en[k] === undefined) throw new Error(`i18n/locales/bg.json: ${k} is not in en.json`)
    out.push(row([`\`${k}\``, cell(en[k]), cell(bg[k]!)]))
  }
  return `${out.join('\n')}\n`
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]).toLowerCase() : ''
if (import.meta.filename && invokedPath === import.meta.filename.toLowerCase()) {
  writeFileSync(UNREVIEWED_BG_MD_PATH, renderUnreviewedBgMd(), 'utf8')
  const ui = Object.keys(readMessages('bg')).length
  console.log(`Wrote ${UNREVIEWED_BG_MD_PATH}: ${UNREVIEWED_BG.length} page strings, ${ui} UI strings.`)
}
